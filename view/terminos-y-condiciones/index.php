					<h2><li>Descripción del Servicio</li></h2>
					<p>La aplicación de WhatsApp de la Biblioteca Digital Ebooks7-24 Plus es un canal de atención automatizado diseñado para facilitar a los usuarios de instituciones educativas suscriptoras el acceso rápido y asistido al contenido académico disponible en su colección contratada.</p>
