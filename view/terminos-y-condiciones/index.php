						<b><li>Funcionalidad Principal</li></b>
						<p>El servicio funciona como un asistente conversacional automatizado que permite al usuario:</p>
						<ul>
							<li>Realizar consultas mediante palabras clave o términos académicos relacionados con las materias de su interés.</li>
							<li>Recibir en tiempo real enlaces directos a los títulos y materiales que correspondan a su búsqueda, de acuerdo con los recursos contratados por su institución.</li>

						</ul>

